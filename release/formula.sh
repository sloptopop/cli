#!/bin/sh
# Prints the Homebrew formula of a release (for sloptopop/homebrew-tap,
# Formula/sloptopop.rb) from its SHA256SUMS.
#   release/formula.sh <version> <SHA256SUMS>
set -eu
version=${1:?usage: release/formula.sh <version> <SHA256SUMS>}
sums=${2:?usage: release/formula.sh <version> <SHA256SUMS>}
version=${version#v}
base=https://github.com/sloptopop/cli/releases/download/v$version
sum() {
  s=$(awk -v f="sloptopop-$1.tar.gz" '$2 == f || $2 == "*" f { print $1 }' "$sums")
  [ -n "$s" ] || { echo "formula: sloptopop-$1.tar.gz not in $sums" >&2; exit 65; }
  echo "$s"
}
cat <<RUBY
# Generated by sloptopop/cli release/formula.sh for v$version; do not edit.
class Sloptopop < Formula
  desc "Checks a codebase on the sloptopop server and applies its verified fixes"
  homepage "https://github.com/sloptopop/cli"
  version "$version"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$base/sloptopop-aarch64-apple-darwin.tar.gz"
      sha256 "$(sum aarch64-apple-darwin)"
    end
    on_intel do
      url "$base/sloptopop-x86_64-apple-darwin.tar.gz"
      sha256 "$(sum x86_64-apple-darwin)"
    end
  end

  on_linux do
    on_arm do
      url "$base/sloptopop-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$(sum aarch64-unknown-linux-musl)"
    end
    on_intel do
      url "$base/sloptopop-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$(sum x86_64-unknown-linux-musl)"
    end
  end

  uses_from_macos "curl"

  def install
    bin.install "sloptopop", "sloptopop-local"
  end

  test do
    assert_match "sloptopop #{version}", shell_output("#{bin}/sloptopop --version")
    assert_match version.to_s, shell_output("#{bin}/sloptopop-local --version")
  end
end
RUBY
